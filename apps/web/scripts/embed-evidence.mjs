/**
 * Regenerates src/lib/embeddedEvidence.ts from data/evidence.
 *
 * Bundles are embedded rather than read at runtime because a serverless
 * function's working directory is not the repository's, and a relative lookup
 * that resolves locally can resolve to nothing in production. A 404 on a URI
 * that an on-chain hash points at is the one failure this project cannot have,
 * so the bundles ship inside the function instead of beside it.
 *
 * Run after publishing new attestations:
 *   node scripts/embed-evidence.mjs
 */
import fs from 'node:fs'
import path from 'node:path'

const dir = 'data/evidence'
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()

let out = `/**
 * Evidence bundles for every attestation Hallmark has written on chain.
 *
 * Each key is keccak256 over exactly these bytes, and that hash is what the
 * ERC-8004 Reputation Registry records beside the attestation. Generated by
 * scripts/embed-evidence.mjs — do not edit by hand.
 */
export const EMBEDDED_EVIDENCE: Readonly<Record<string, string>> = Object.freeze({
`

for (const file of files) {
  const hash = path.basename(file, '.json')
  const text = fs.readFileSync(path.join(dir, file), 'utf8')
  out += `  ${JSON.stringify(hash)}: ${JSON.stringify(text)},\n`
}

out += '})\n'

fs.writeFileSync('src/lib/embeddedEvidence.ts', out)
console.log(`embedded ${files.length} bundles (${(out.length / 1024).toFixed(0)} KB)`)
